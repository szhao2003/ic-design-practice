import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
const questions=JSON.parse(await readFile('src/data/questions/13-programming-tools.json','utf8'));
const question=questions.find(q=>q.id==='ADAPTED-TOOLSFPGA-TOOLS-0001');
const shown=question?.referenceAnswerMd.match(/```python\s*\n([\s\S]*?)```/)?.[1];
const tested=await readFile('examples/python/slack_summary.py','utf8');
if(shown?.replaceAll('\r','').trim()!==tested.replaceAll('\r','').trim())throw new Error('Python 网页参考答案与测试文件不一致');
const python=process.platform==='win32'?'python':'python3';
const result=spawnSync(python,['-B','tests/python_reference_test.py'],{stdio:'inherit',timeout:30000});
if(result.error||result.status!==0)throw new Error(`Python 参考代码测试失败：${result.error?.message??result.status}`);
console.log('Python reference: exact published code + 6 runtime tests PASS.');
